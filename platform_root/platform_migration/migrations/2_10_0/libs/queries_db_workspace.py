# AI Conversation テーブル作成
CREATE_TABLE_AI_CONVERSATION = """
CREATE TABLE IF NOT EXISTS T_CHAT_CONVERSATION
(
  CONVERSATION_ID VARCHAR(36) NOT NULL COMMENT 'Conversation ID (ULID)',
  PROMPT_PROFILE VARCHAR(64) NOT NULL COMMENT 'プロンプトプロファイル: AgenticAI/LLMEditor (システムプロンプト切り替え用)',
  USER_ID VARCHAR(256) NOT NULL COMMENT 'User ID',
  AI_SERVICE_ID VARCHAR(64) NOT NULL COMMENT 'AIサービスID: bedrock-cache, bedrock, openai, etc.',
  MODEL_ID VARCHAR(255) NOT NULL COMMENT 'デフォルトで使用するモデルID (completionsでmodel_id省略時に使用)',
  TOOLS LONGTEXT NULL COMMENT 'ツール定義 (JSON配列、Anthropic tools形式。未指定時はNULL)',
  TITLE VARCHAR(255) NOT NULL COMMENT '会話タイトル',
  STATUS VARCHAR(32) NOT NULL DEFAULT 'active' COMMENT 'ステータス: active/closed/archived',
  CURRENT_TOKEN_COUNT INT DEFAULT 0 COMMENT '現在のトークン数（累積）',
  CREATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
  CREATE_USER VARCHAR(40) COMMENT '作成ユーザー',
  LAST_UPDATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最終更新日時',
  LAST_UPDATE_USER VARCHAR(40) COMMENT '最終更新ユーザー',
  PRIMARY KEY (CONVERSATION_ID),
  INDEX IDX_USER_PROMPT_UPDATED (USER_ID, PROMPT_PROFILE, LAST_UPDATE_TIMESTAMP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AIチャット会話'
"""

# AI Message テーブル作成
CREATE_TABLE_AI_MESSAGE = """
CREATE TABLE IF NOT EXISTS T_CHAT_MESSAGE
(
  MESSAGE_ID VARCHAR(36) NOT NULL COMMENT 'Message ID (ULID)',
  CONVERSATION_ID VARCHAR(36) NOT NULL COMMENT 'Conversation ID',
  MESSAGE_SEQ INT NOT NULL COMMENT 'メッセージ順序番号',
  CONTENTS LONGTEXT NOT NULL COMMENT 'コンテンツ（JSON配列）',
  CREATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
  CREATE_USER VARCHAR(40) COMMENT '作成ユーザー',
  LAST_UPDATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最終更新日時',
  LAST_UPDATE_USER VARCHAR(40) COMMENT '最終更新ユーザー',
  PRIMARY KEY (MESSAGE_ID),
  UNIQUE KEY UK_CONV_MSG_SEQ (CONVERSATION_ID, MESSAGE_SEQ),
  CONSTRAINT FK_MESSAGE_CONVERSATION FOREIGN KEY (CONVERSATION_ID)
    REFERENCES T_CHAT_CONVERSATION(CONVERSATION_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AIチャットメッセージ'
"""

# User Lesson テーブル作成（ワークスペース単位）
CREATE_TABLE_USER_LESSON = """
CREATE TABLE IF NOT EXISTS T_USER_LESSON
(
  LESSON_ID VARCHAR(36) NOT NULL COMMENT 'Lesson ID (ULID)',
  USER_ID VARCHAR(256) NOT NULL COMMENT 'User ID',
  LESSON LONGTEXT NOT NULL COMMENT '学習事項の内容',
  CATEGORY VARCHAR(255) NULL COMMENT '分類',
  PROMPT_PROFILE VARCHAR(20) NULL COMMENT 'システムプロンプトへの反映対象prompt_profile (NULL=全プロファイル共通)',
  PRIORITY TINYINT NOT NULL DEFAULT 5 COMMENT '重要度 (1:最低 〜 10:最高)',
  ENABLED TINYINT(1) NOT NULL DEFAULT 1 COMMENT '有効/無効フラグ (システムプロンプトへの反映有無)',
  CONVERSATION_ID VARCHAR(36) NULL COMMENT '学習元の会話ID',
  CREATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
  CREATE_USER VARCHAR(40) COMMENT '作成ユーザー',
  LAST_UPDATE_TIMESTAMP DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最終更新日時',
  LAST_UPDATE_USER VARCHAR(40) COMMENT '最終更新ユーザー',
  PRIMARY KEY (LESSON_ID),
  INDEX IDX_USER_ENABLED_PRIORITY (USER_ID, ENABLED, PRIORITY, LAST_UPDATE_TIMESTAMP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AIアシスタント 学習事項(ワークスペース単位)'
"""

